import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const harnessModule = "./browser-harness.ts";
const { withBrowserWorkflow }: typeof import("./browser-harness") = await import(harnessModule);

await withBrowserWorkflow(3025, async (browser, url) => {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(10_000);
  page.on('pageerror', error => console.error('picker page error', error));
  await page.goto(url);
  await page.locator('#scqa-answer').fill('Keep my current writing');
  await page.getByRole('tab', { name: /Gather Facts/ }).click();
  for (const [finding, citation] of [['Rail delays fell by half', 'Field notebook, page 9'], ['Unfinished research', '']]) {
    await page.getByRole('button', { name: 'Add fact' }).click();
    const card = page.locator('.fact-card').last();
    await card.getByLabel('Fact text', { exact: true }).fill(finding!);
    await card.getByLabel('Descriptive citation', { exact: true }).fill(citation!);
  }
  await page.getByRole('tab', { name: /Construct Argument/ }).click();
  const situation = page.getByLabel('Facts supporting Situation', { exact: true });
  await situation.locator(':scope > summary').click();
  const trigger = situation.getByText('Choose Gathered Facts', { exact: true });
  await trigger.focus();
  await trigger.press('Enter');
  const search = situation.getByRole('searchbox', { name: 'Search facts to attach' });
  assert.equal(await search.evaluate(el => el === document.activeElement), true, 'Opening the picker focuses search');
  await search.fill('notebook');
  const result = situation.getByRole('article', { name: 'Gathered Fact 1' });
  assert.match(await result.innerText(), /Rail delays fell by half/);
  assert.match(await result.innerText(), /Source reference.*Field notebook, page 9/);
  assert.match(await result.innerText(), /Unused/);
  await result.getByRole('button', { name: 'Attach fact', exact: true }).focus();
  await page.keyboard.press('Enter');
  assert.equal(await situation.locator('.attached-fact').count(), 1);
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  assert.equal(await page.locator('#scqa-answer').inputValue(), 'Keep my current writing');
  assert.equal(await page.getByLabel('Facts supporting Complication', { exact: true }).locator('.attached-fact').count(), 0);
  assert.equal(await page.getByRole('tab', { name: /Construct Argument/ }).getAttribute('aria-selected'), 'true');
  console.log('fact-picker-05: source search, citation-only keyboard attachment, destination, writing and focus passed');
  await mkdir('output/playwright/fact-picker-05', { recursive: true });
  await trigger.click();
  assert.match(await situation.getByRole('article', { name: 'Gathered Fact 1', exact: true }).innerText(), /Already attached here/);
  assert.match(await situation.getByRole('article', { name: 'Gathered Fact 1', exact: true }).innerText(), /Used in Situation/);
  const incomplete = situation.getByRole('article', { name: 'Gathered Fact 2', exact: true });
  assert.match(await incomplete.innerText(), /Incomplete/);
  assert.equal(await incomplete.getByRole('button', { name: 'Attach fact', exact: true }).count(), 0);
  await search.fill('no such research');
  assert.match(await situation.innerText(), /No matching facts/);
  await situation.getByRole('button', { name: 'Clear search' }).click();
  assert.equal(await search.inputValue(), '');
  assert.equal(await search.evaluate(el => el === document.activeElement), true);
  await search.fill('delays');
  assert.equal(await situation.getByRole('article', { name: /Gathered Fact/ }).count(), 1);
  await search.press('Escape');
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  await trigger.click();
  await situation.getByRole('button', { name: 'View attached fact' }).click();
  assert.equal(await situation.locator('.attached-fact').getByText('Edit fact', { exact: true }).evaluate(el => el === document.activeElement), true);
  await trigger.click();
  await page.screenshot({ path: 'output/playwright/fact-picker-05/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await search.fill('Unfinished');
  await page.screenshot({ path: 'output/playwright/fact-picker-05/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await incomplete.getByRole('button', { name: 'Complete this fact' }).click();
  const editor = page.locator('.fact-card').last();
  assert.equal(await editor.getByRole('textbox', { name: 'Fact text', exact: true }).evaluate(el => el === document.activeElement), true);
  await editor.getByLabel('Descriptive citation', { exact: true }).fill('Interview notes, page 2');
  await page.getByRole('tab', { name: /Construct Argument/ }).click();
  const argument = page.locator('[data-disclosure="destination-argument-1"]');
  await argument.locator(':scope > summary').click();
  await argument.getByText('Choose Gathered Facts', { exact: true }).click();
  await argument.getByRole('searchbox', { name: 'Search facts to attach' }).fill('Interview');
  await argument.getByRole('button', { name: 'Attach fact', exact: true }).click();
  assert.match(await argument.locator('.attached-fact').innerText(), /Unfinished research/);
  assert.equal(await situation.locator('.attached-fact').count(), 1);
  assert.equal(await page.locator('#scqa-answer').inputValue(), 'Keep my current writing');
  console.log('fact-picker-05: mixed status, text search, no-results recovery, Escape, attached focus, mobile and incomplete recovery passed');
  await argument.getByText('Choose Gathered Facts', { exact: true }).click();
  await argument.getByRole('article', { name: 'Gathered Fact 1', exact: true }).getByRole('button', { name: 'Attach fact', exact: true }).click();
  await situation.locator('.attached-fact').getByText('Edit fact', { exact: true }).click();
  const sharedText = situation.locator('.attached-fact').getByRole('textbox', { name: 'Fact text', exact: true });
  await sharedText.fill('A shared finding');
  assert.match(await argument.locator('.attached-fact').last().innerText(), /A shared finding/);
  await sharedText.press('End');
  await sharedText.pressSequentially('!');
  await trigger.click();
  await search.press('Escape');
  await sharedText.focus();
  await sharedText.press('Control+z');
  assert.equal(await sharedText.inputValue(), 'A shared finding', 'Picker use retains native text undo');
  assert.match(await argument.locator('.attached-fact').last().innerText(), /A shared finding/);
  console.log('fact-picker-05: canonical shared summaries and native undo survive picker use');
  const emptyPage = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await emptyPage.goto(url);
  const empty = emptyPage.getByLabel('Facts supporting Situation', { exact: true });
  await empty.locator(':scope > summary').click();
  await empty.getByText('Choose Gathered Facts', { exact: true }).click();
  assert.match(await empty.innerText(), /No facts gathered yet/);
  await empty.getByRole('button', { name: 'Create new fact here' }).click();
  assert.equal(await empty.locator('.attached-fact').getByLabel('Fact text', { exact: true }).evaluate(el => el === document.activeElement), true);
  console.log('fact-picker-05: empty research recovery creates at the intended destination');
});
