import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const harnessModule = "./browser-harness.ts";
const { withBrowserWorkflow }: typeof import("./browser-harness") = await import(harnessModule);

await withBrowserWorkflow(3022, async (browser, url) => {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(8000);
  await page.goto(url);
  for (const id of ["scqa-question", "scqa-answer"]) assert.equal(await page.locator(`#${id}`).isVisible(), true);
  assert.equal(await page.getByRole("heading", { name: "Supporting Arguments", exact: true }).isVisible(), true);
  const context = page.locator("details").filter({ has: page.locator("summary").filter({ hasText: /^Context/ }) });
  const planning = page.locator("details").filter({ has: page.locator("summary").filter({ hasText: /^Planning/ }) });
  assert.equal(await context.count(), 1, "Context is available as a disclosure");
  assert.equal(await page.locator("#scqa-situation").isVisible(), false);
  assert.equal(await page.locator("#planning-audience").isVisible(), false);
  await mkdir("output/playwright/focused-construction-02", { recursive: true });
  await page.screenshot({ path: "output/playwright/focused-construction-02/fresh-desktop.png", fullPage: true });
  await context.locator(":scope > summary").press("Enter");
  await page.locator("#scqa-situation").fill("Demand is rising.");
  await page.locator("#scqa-situation").press("Tab");
  await page.locator("#scqa-complication").fill("Capacity is fixed.");
  await context.locator(":scope > summary").press("Space");
  assert.match(await context.locator(":scope > summary").innerText(), /Situation: Demand is rising/);
  assert.match(await context.locator(":scope > summary").innerText(), /Complication: Capacity is fixed/);
  await planning.locator(":scope > summary").press("Enter");
  await page.locator("#planning-audience").fill("Private managers");
  await page.locator("#planning-outcome").fill("Private approval");
  await planning.locator(":scope > summary").press("Enter");
  assert.match(await planning.locator(":scope > summary").innerText(), /Audience: Private managers/);
  assert.match(await planning.locator(":scope > summary").innerText(), /Intended outcome: Private approval/);
  await page.getByRole("button", { name: "+ Argument", exact: true }).click();
  assert.equal(await page.locator("#scqa-situation").isVisible(), false);
  assert.equal(await page.locator("#planning-audience").isVisible(), false);
  await context.locator(":scope > summary").click();
  assert.equal(await page.locator("#scqa-situation").inputValue(), "Demand is rising.");
  assert.equal(await page.locator("#scqa-complication").inputValue(), "Capacity is fixed.");
  console.log("focused-construction-02: fresh fields, keyboard disclosures and populated summaries passed");
  await page.goto(url);
  await page.getByRole("button", { name: "Reasoning review", exact: true }).click();
  await page.getByRole("button", { name: "Add what is happening.", exact: true }).click();
  assert.equal(await page.locator("#scqa-situation").evaluate(el => el === document.activeElement), true, "Review opens Context before focusing an issue");
  const answerSize = await page.locator('label[for="scqa-answer"]').evaluate(el => parseFloat(getComputedStyle(el.querySelector("span")!).fontSize));
  const reasonSize = await page.getByRole("textbox", { name: /Why should someone believe this/ }).evaluate(el => parseFloat(getComputedStyle(el.closest("label")!.querySelector("span")!).fontSize));
  assert.ok(answerSize > reasonSize, "Answer has stronger type hierarchy than supporting reasons");
  const situation = page.locator("#scqa-situation");
  await situation.pressSequentially("!");
  await context.locator(":scope > summary").click();
  await context.locator(":scope > summary").click();
  await situation.focus();
  await situation.press("Control+z");
  assert.equal(await situation.inputValue(), "", "Native undo remains in the framing editor");
  await situation.fill("Context retained");
  await situation.press("Home");
  await situation.press("Shift+ArrowRight");
  await page.getByRole("button", { name: "Reasoning review", exact: true }).click();
  await page.getByRole("button", { name: "Back to editing", exact: true }).click();
  assert.equal(await situation.evaluate(el => el === document.activeElement), true);
  assert.deepEqual(await situation.evaluate((el: HTMLTextAreaElement) => [el.selectionStart, el.selectionEnd]), [0, 1]);
  await page.getByRole("checkbox", { name: "Save draft in this browser" }).check();
  await page.reload();
  assert.equal(await situation.isVisible(), false, "Restored boards start with Context collapsed");
  assert.match(await context.locator(":scope > summary").innerText(), /Context retained/);
  await context.locator(":scope > summary").click();
  await page.getByRole("button", { name: "+ Argument", exact: true }).click();
  assert.equal(await situation.isVisible(), true, "Open Context survives rerendering");
  assert.equal(await situation.inputValue(), "Context retained");
  await page.getByRole("tab", { name: /Gather Facts/ }).click();
  await page.getByRole("button", { name: "+ Add fact", exact: true }).click();
  await page.getByRole("textbox", { name: "Fact text", exact: true }).fill("Shared contextual evidence");
  await page.getByRole("textbox", { name: "Descriptive citation", exact: true }).fill("Field notebook, p. 8");
  await page.getByRole("tab", { name: /Construct Argument/ }).click();
  const destination = page.locator('[data-disclosure="destination-situation"]');
  await destination.locator(":scope > summary").click();
  await destination.getByRole("combobox").selectOption("fact-1");
  await context.locator(":scope > summary").click();
  await context.locator(":scope > summary").click();
  assert.match(await destination.innerText(), /Shared contextual evidence/);
  await page.locator("#scqa-question").fill("How should we meet rising demand?");
  await page.locator("#scqa-answer").fill("Run a limited pilot before expanding capacity.");
  await page.getByRole("textbox", { name: /Why should someone believe this/ }).first().fill("A pilot tests demand before a larger commitment.");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "output/playwright/focused-construction-02/desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await situation.fill("Long framing " + "unbrokencontent".repeat(35));
  await context.locator(":scope > summary").click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "output/playwright/focused-construction-02/mobile.png", fullPage: true });
  console.log("focused-construction-02: hierarchy, native undo, review return, draft summaries, attachments and responsive fit passed");
  await page.close();
  for (const [module, method] of [["./question-first.ts", "verifyQuestionFirst"], ["./planning-context.ts", "verifyPlanningContext"], ["./review-navigation-06.ts", "verifyReviewNavigation06"], ["./reasoning-review.ts", "verifyReasoningReview"]]) {
    const workflow = await import(module!);
    await workflow[method!](browser, url);
    console.log(`focused-construction-02: ${method} passed`);
  }
});

